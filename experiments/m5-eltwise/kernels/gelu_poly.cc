// A 4096-element variant, because the tile size turned out to be the cost.
//
// At batch 64 GELU moved 25 MB per call in 16.5 ms -- 1.5 GB/s against the
// 33 GB/s tasks/0010 measured -- and 21.5 us per 1024-element tile against
// roughly 2 us of arithmetic. That is per-transaction overhead, not bandwidth
// and not compute, so the fix is fewer and larger transactions.
//
// L1 budget (trap 3): 2 fifos x depth 2 x 4096 x 2 B = 32 KB of 64 KB.
void gelu_poly_bf16_4k(bfloat16 *restrict input, bfloat16 *restrict output) {
  gelu_poly_impl(input, output, 4096);
}

// SPEED PROBE ONLY -- numerically wrong on purpose. Do not ship.
//
// GELU costs 9.4 ms where a passthrough moving the same bytes over the same
// columns costs 0.52 ms, so it is compute bound by 18x. This asks WHAT the
// compute is: same structure, same four interleaved chains, same bf16<->f32
// widen and narrow, but the Horner chain cut from 8 steps to 2.
//
//   time scales with degree  -> the srs chain is the cost, and Estrin or a
//                               lower degree is a real lever
//   time barely moves        -> the widen/narrow or loop overhead dominates and
//                               shortening the polynomial buys nothing
void gelu_probe_deg2_bf16(bfloat16 *restrict input, bfloat16 *restrict output) {
  gelu_poly_impl_deg2(input, output, 1024);
}

